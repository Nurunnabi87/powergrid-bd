"use client";

import { useState } from "react";
import { useSearchParams } from "next/navigation";
import { useQuery } from "@tanstack/react-query";
import type { ColumnDef } from "@tanstack/react-table";
import { Ban, CalendarX2, CheckCheck, MoreHorizontal, Play, RotateCcw, Trash2, Wand2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { ConfirmDialog } from "@/components/shared/confirm-dialog";
import { DataTable } from "@/components/shared/data-table";
import { DateFilter } from "@/components/shared/date-filter";
import { EmptyState } from "@/components/shared/empty-state";
import { ErrorState } from "@/components/shared/error-state";
import { FilterSelect, type FilterOption } from "@/components/shared/filter-select";
import { PaginationBar } from "@/components/shared/pagination-bar";
import { StatusBadge } from "@/components/shared/status-badge";
import { useApiMutation } from "@/hooks/use-api-mutation";
import { useUrlState } from "@/hooks/use-url-state";
import { api } from "@/lib/api/client";
import { errorMessage } from "@/lib/api/errors";
import { formatCalendarDate, formatTime } from "@/lib/format";
import { queryKeys } from "@/lib/query/keys";
import { scheduleParams } from "@/lib/query/schedule-params";
import { SCHEDULE_STATUSES, SCHEDULE_TRANSITIONS, type Schedule, type ScheduleStatus } from "@/types/domain";

type PendingAction = { schedule: Schedule; kind: "status"; status: ScheduleStatus } | { schedule: Schedule; kind: "delete" };

const STATUS_ACTION: Partial<Record<ScheduleStatus, { label: string; icon: typeof Play; destructive?: boolean }>> = {
  ACTIVE: { label: "Start shedding now", icon: Play },
  COMPLETED: { label: "Mark completed", icon: CheckCheck },
  CANCELLED: { label: "Cancel slot", icon: Ban, destructive: true },
};

export function ScheduleTable({ zones }: { zones: FilterOption[] }) {
  const searchParams = useSearchParams();
  const { reset } = useUrlState();
  const params = scheduleParams(searchParams);
  const [pending, setPending] = useState<PendingAction | null>(null);

  const query = useQuery({
    queryKey: queryKeys.schedules.list(params),
    queryFn: ({ signal }) => api.list<Schedule>("/schedules", params, signal),
    placeholderData: (previous) => previous,
  });

  const changeStatus = useApiMutation<unknown, { id: string; status: ScheduleStatus }>({
    mutationFn: ({ id, status }) => api.patch(`/schedules/${id}/status`, { status }),
    invalidate: [queryKeys.schedules.all],
    successMessage: "Schedule updated",
    onSuccess: () => setPending(null),
  });

  const remove = useApiMutation<unknown, string>({
    mutationFn: (id) => api.delete(`/schedules/${id}`),
    invalidate: [queryKeys.schedules.all],
    successMessage: "Schedule deleted",
    onSuccess: () => setPending(null),
  });

  const columns: ColumnDef<Schedule, unknown>[] = [
    {
      id: "when",
      header: "When",
      cell: ({ row }) => (
        <div className="whitespace-nowrap">
          <p className="font-medium tabular-nums">
            {formatTime(row.original.startTime)} – {formatTime(row.original.endTime)}
          </p>
          <p className="text-xs text-muted-foreground">{formatCalendarDate(row.original.date)}</p>
        </div>
      ),
    },
    {
      id: "feeder",
      header: "Feeder",
      cell: ({ row }) => (
        <div className="min-w-40">
          <p className="font-medium">
            {row.original.feeder.name} <span className="font-mono text-xs text-muted-foreground">{row.original.feeder.code}</span>
          </p>
          <p className="text-xs text-muted-foreground">
            {row.original.feeder.substation.zone.name} · {row.original.feeder.substation.name}
          </p>
        </div>
      ),
    },
    { id: "status", header: "Status", cell: ({ row }) => <StatusBadge status={row.original.status} /> },
    {
      id: "source",
      header: "Source",
      cell: ({ row }) =>
        row.original.isAutoGenerated ? (
          <span className="inline-flex items-center gap-1 text-sm">
            <Wand2 className="size-3.5" aria-hidden /> Generated
          </span>
        ) : (
          <span className="text-sm text-muted-foreground">Manual</span>
        ),
    },
    {
      id: "reason",
      header: "Reason",
      cell: ({ row }) => <span className="line-clamp-1 max-w-56 text-sm text-muted-foreground">{row.original.reason ?? "—"}</span>,
    },
    {
      id: "actions",
      header: () => <span className="sr-only">Actions</span>,
      cell: ({ row }) => {
        const schedule = row.original;
        const next = SCHEDULE_TRANSITIONS[schedule.status];
        const canDelete = schedule.status !== "ACTIVE";
        if (!next.length && !canDelete) return null;
        return (
          <div className="flex justify-end">
            <DropdownMenu>
              <DropdownMenuTrigger asChild>
                <Button variant="ghost" size="icon" aria-label="Schedule actions">
                  <MoreHorizontal />
                </Button>
              </DropdownMenuTrigger>
              <DropdownMenuContent align="end">
                {next.map((status) => {
                  const action = STATUS_ACTION[status];
                  if (!action) return null;
                  return (
                    <DropdownMenuItem
                      key={status}
                      variant={action.destructive ? "destructive" : "default"}
                      onSelect={() => setPending({ schedule, kind: "status", status })}
                    >
                      <action.icon /> {action.label}
                    </DropdownMenuItem>
                  );
                })}
                {canDelete && (
                  <>
                    {next.length > 0 && <DropdownMenuSeparator />}
                    <DropdownMenuItem variant="destructive" onSelect={() => setPending({ schedule, kind: "delete" })}>
                      <Trash2 /> Delete
                    </DropdownMenuItem>
                  </>
                )}
              </DropdownMenuContent>
            </DropdownMenu>
          </div>
        );
      },
    },
  ];

  const hasFilters = ["zoneId", "status", "date"].some((key) => searchParams.get(key));

  return (
    <div className="space-y-4">
      <div className="flex flex-col gap-2 sm:flex-row sm:flex-wrap">
        <FilterSelect param="zoneId" label="Zones" options={zones} />
        <FilterSelect param="status" label="Status" options={SCHEDULE_STATUSES} />
        <DateFilter param="date" label="Date" />
        {hasFilters && (
          <Button variant="ghost" onClick={() => reset()}>
            <RotateCcw /> Reset
          </Button>
        )}
      </div>

      {query.isError && !query.data ? (
        <ErrorState message={errorMessage(query.error)} onRetry={() => query.refetch()} />
      ) : (
        <>
          <DataTable
            columns={columns}
            data={query.data?.data ?? []}
            isLoading={query.isPending}
            isFetching={query.isFetching}
            getRowId={(schedule) => schedule.id}
            empty={
              <EmptyState
                icon={CalendarX2}
                title={hasFilters ? "No slots match these filters" : "No load-shedding slots"}
                description={hasFilters ? "Try another date or zone." : "Publish a slot manually or generate a day's schedule for a zone."}
                action={hasFilters ? <Button variant="outline" onClick={() => reset()}>Clear filters</Button> : undefined}
              />
            }
          />
          {query.data && <PaginationBar meta={query.data.meta} noun="slots" />}
        </>
      )}

      <ConfirmDialog
        open={pending?.kind === "status"}
        onOpenChange={(open) => !open && setPending(null)}
        title={pending?.kind === "status" ? `${STATUS_ACTION[pending.status]?.label ?? "Update"}?` : ""}
        description={
          pending?.kind === "status" && pending.status === "CANCELLED"
            ? "Customers on this feeder keep their power during this slot. This can't be undone."
            : "The slot's status will change for customers viewing the schedule."
        }
        confirmLabel={pending?.kind === "status" ? STATUS_ACTION[pending.status]?.label : "Confirm"}
        destructive={pending?.kind === "status" && pending.status === "CANCELLED"}
        loading={changeStatus.isPending}
        onConfirm={() => pending?.kind === "status" && changeStatus.mutate({ id: pending.schedule.id, status: pending.status })}
      />
      <ConfirmDialog
        open={pending?.kind === "delete"}
        onOpenChange={(open) => !open && setPending(null)}
        title="Delete this slot?"
        description="It disappears from every schedule view. Active slots can't be deleted."
        confirmLabel="Delete"
        destructive
        loading={remove.isPending}
        onConfirm={() => pending?.kind === "delete" && remove.mutate(pending.schedule.id)}
      />
    </div>
  );
}
